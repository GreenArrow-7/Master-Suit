-- Permission catalogue: definitions only.
--
-- A "Permission" row defines a (module, action) pair that a role CAN be granted.
-- It grants nothing: authority exists only in "RolePermission". This migration
-- inserts no "RolePermission" row and changes no role.
--
-- Why: on a clean install — migrations, bootstrap-owner, a workspace created
-- through the platform API, no demo seed — 25 pairs the code checks had no row
-- (for example tickets:VIEW, documents:VIEW, products:VIEW, forms:VIEW,
-- automation:VIEW, leads:EXPORT), so those screens could be granted to nobody.
-- Databases that ran the demo seed or provisioned workspaces already hold most of
-- these rows; ON CONFLICT leaves every existing row, and its id, untouched.
--
-- The list is src/lib/security/permissionCatalogue.ts (478 definitions):
-- the seed's record and admin catalogues, the workspace-provisioning floor, and
-- every pair an earlier migration inserted. tests/unit/permission-catalogue.spec.ts
-- keeps this file and that list identical.
--
-- Operators: new definitions appear in the role editor as "None" for every
-- existing role. Do NOT run scripts/backfill-admin-permissions.mjs or
-- scripts/seed-role-defaults.ts afterwards — both grant every catalogue row and
-- would widen existing roles. A workspace created after this migration gives its
-- company_admin every catalogue permission, as provisioning always has.

